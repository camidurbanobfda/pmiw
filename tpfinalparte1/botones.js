function mouseClicked(){
  
  if(dentroDelBotonSeguirDerecho && dialogoActual == 20){
    pantallaActual = 11;
    dialogoActual = 21;
  }
  
  if(dentroDelBotonBuscarOtrosCaminos && dialogoActual == 20){
    pantallaActual = 13;
    dialogoActual = 23;
  }
  
  if(dentroDelBotonSiguiente && (dialogoActual == 9 || dialogoActual == 11 || dialogoActual == 16 || dialogoActual == 18 || dialogoActual == 22 || dialogoActual == 26 || dialogoActual == 27 || dialogoActual == 29 || dialogoActual == 35 || dialogoActual == 42 || dialogoActual == 45 || dialogoActual == 50)){
   //para cuando la flecha tiene que cambiar la pantalla además del diálogo.
    pantallaActual++;
    dialogoActual++;
    }else if(dentroDelBotonSiguiente && dialogoActual == 15){ //para que al evadir a las ratas se conecte con el otro camino y lleve a las cloacas.
    pantallaActual = 14;
    dialogoActual = 26;
  }else if(dentroDelBotonSiguiente && dialogoActual != 4 && dialogoActual != 6 && dialogoActual != 25 && dialogoActual != 33 && dialogoActual != 40 && dialogoActual != 44 && dialogoActual != 48){
    //para que en los diálogos aclarados no se pueda usar la flecha para avanzar (es cuando hay que hacer elecciones).
    dialogoActual++;
  }
  
  if(dentroDelCaminoQueso && dialogoActual == 4){
    pantallaActual = 2;
    dialogoActual = 5;
  }
  
  if(dentroDelCaminoSalame && dialogoActual == 4){
    pantallaActual = 8;
    dialogoActual = 16;
  }
  
  if(dentroDelCaminoAnana && dialogoActual == 4){
    pantallaActual = 22;
    dialogoActual = 38;
  }
  
  if(dentroDelBotonSplinter && dialogoActual == 6){
    pantallaActual++;
    dialogoActual++;
  }
  
  if(dentroDelBotonPelearSolos && dialogoActual == 6){
    pantallaActual = 4;
    dialogoActual = 9;
  }
  
  if(dentroDelBotonEvadir && dialogoActual == 6){
    pantallaActual = 7;
    dialogoActual = 14;
  }
  
  if(dentroDelCaminoAgua && dialogoActual == 25){
    pantallaActual = 14;
    dialogoActual = 26;
  }
  
  if(dentroDeEscalera1 && dialogoActual == 25){
    pantallaActual = 18;
    dialogoActual = 32;
  }
  
  if(dentroDeLocal && dialogoActual == 33){
    pantallaActual = 19;
    dialogoActual = 34;
  }
  
  if(dentroDeCallejon && dialogoActual == 33){
    pantallaActual = 20;
    dialogoActual = 35;
  }
  
  if(dentroDelBotonRechazar && dialogoActual == 40){
    pantallaActual = 23;
    dialogoActual = 41;
  }
  
  if(dentroDelBotonSeguirAKarai && dialogoActual == 40){
    pantallaActual = 25;
    dialogoActual = 45;
  }
  
  if(dentroDeEscalera2 && dialogoActual == 44){
    pantallaActual = 18;
    dialogoActual = 32;
  }
  
  if(dentroDelBotonQuedarse && dialogoActual == 48){
    pantallaActual = 27;
    dialogoActual = 49;
  }
  
  if(dentroDelBotonCorrer && dialogoActual == 48){
    pantallaActual = 28;
    dialogoActual = 50;
  }
  
}
